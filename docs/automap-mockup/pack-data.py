#!/usr/bin/env python3
"""Build automap-mockup.html from the page sources and the map data.

The page is page/head.html, page/map.js and page/ui.js. The data is what the real map code shows
for one or more saves, written by the game itself (src/AutoMapExport.cpp): per save, index.json
and one draw list per level, vision and spoiler level (L<level>_v<vision>_s<spoilers>.json;
vision 0 fog, 1 explored live, 2 whole level; spoilers 0 All, 1 Learned, 2 Seen), with every
cell's tooltip and links, plus the game's pictures as .bmp.

Change only the drawing (page/*), keep the data:
    python3 -I pack-data.py
New data (another save, a custom dungeon, or after the map code changed):
1. Build the game: cd src && make RELEASE=1
2. In a game folder (dungeon.dat, graphics.dat, the save and its .map), per save:
     printf 'save <save>\nat L0 (4,12) facing S light 0\n' > case.txt
     CSB_MAP_EXPORT=<outdir>/<save> <repo>/src/csb --visibility-test case.txt
   It loads the save without a window, writes the export and exits.
3. cd <outdir>/<save>; mkdir -p png; for f in *.bmp; do convert "$f" -strip "png/${f%.bmp}.png"; done
   (-strip leaves out the time ImageMagick writes, so the same pictures give the same page)
4. python3 -I pack-data.py <outdir>/<save> [<outdir>/<save2> ...]
   The save buttons in page/head.html name the saves in this order.

Every run also writes src/AutoMapExportPage.inc, the page code the game's EXPORT button puts in
its page (with page/export-head.html instead of page/head.html): rebuild the game after a change.

Each save is stored gzip-compressed (the page unpacks it with DecompressionStream), the pictures
once for all saves.
"""
import base64, gzip, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
PAGE = os.path.join(HERE, 'automap-mockup.html')
# The game's EXPORT writes the same page for one save: it carries the page code in this include
GAME_PAGE = os.path.join(HERE, '..', '..', 'src', 'AutoMapExportPage.inc')
RAW_END = ')CSBPAGE"'
DATA_BLOCK = re.compile(r'<script id="data">\n(.*?)\n</script>', re.S)


def pack(dirs):
    sprites = {}
    saves = {}
    for d in dirs:
        name = os.path.basename(os.path.normpath(d))
        index = json.load(open(os.path.join(d, 'index.json')))
        views = {}
        for f in sorted(os.listdir(d)):
            if f.startswith('L') and f.endswith('.json'):
                views[f[:-5]] = json.load(open(os.path.join(d, f)))
        blob = json.dumps({'index': index, 'views': views}, separators=(',', ':')).encode()
        saves[name] = base64.b64encode(gzip.compress(blob, 9, mtime=0)).decode()
        png_dir = os.path.join(d, 'png')
        for f in sorted(os.listdir(png_dir)):
            key = f[:-4] + '.bmp'
            if key not in sprites:
                sprites[key] = 'data:image/png;base64,' + base64.b64encode(open(os.path.join(png_dir, f), 'rb').read()).decode()
    return 'window.MAPDATA=' + json.dumps({'saves': saves, 'sprites': sprites}, separators=(',', ':')) + ';'


def write_game_page():
    part = lambda name: open(os.path.join(HERE, 'page', name)).read()
    def literal(name, text):
        assert RAW_END not in text, name
        return 'static const char *const %s = R"CSBPAGE(%s)CSBPAGE";\n' % (name, text)
    out = ('// Generated by docs/automap-mockup/pack-data.py from docs/automap-mockup/page: do not edit.\n'
           '// The page the map window\'s EXPORT writes (AutoMapExport.cpp); the head has @TITLE@ and\n'
           '// @SUBTITLE@ in it, and the data goes between the head and the code.\n'
           + literal('EXPORT_PAGE_HEAD', part('export-head.html'))
           + literal('EXPORT_PAGE_CODE', part('map.js') + part('ui.js')))
    open(GAME_PAGE, 'w').write(out)
    print('wrote', os.path.normpath(GAME_PAGE), os.path.getsize(GAME_PAGE), 'bytes')


def build(data):
    part = lambda name: open(os.path.join(HERE, 'page', name)).read()
    return (part('head.html') + '<script id="data">\n' + data + '\n</script>\n<script>\n'
            + part('map.js') + part('ui.js') + '\n</script>\n</body></html>\n')


if __name__ == '__main__':
    if sys.argv[1:]:
        data = pack(sys.argv[1:])
    else:
        found = DATA_BLOCK.search(open(PAGE).read())
        if not found:
            sys.exit('automap-mockup.html has no data block; pass export folders')
        data = found.group(1)
    open(PAGE, 'w').write(build(data))
    print('wrote', PAGE, os.path.getsize(PAGE), 'bytes')
    write_game_page()
