def lookup(rn, csb=False):
    """Item name (or None) for a raw 16-bit possession word, mirroring
    MCE's writeitemgad(): 0xFFFF is empty; values whose low 14 bits
    fall outside 0x1000..0x2FFF are invalid; anything unlisted is
    unknown.  Column 0 = DM name, column 1 = CSB name."""
    if rn == 0xFFFF:
        return None
    if (rn & 0x3FFF) < 0x1000 or (rn & 0x3FFF) > 0x2FFF:
        return None
    idx = rn & 0x1FFF
    if not (idx <= 0xFF
            or 0x800 <= idx <= 0x93F
            or 0x1400 <= idx <= 0x14FF
            or 0x1800 <= idx <= 0x18FF):
        return None
    entry = RN_NAMES.get(idx)
    if entry is None:
        return None
    return entry[1] if csb else entry[0]


