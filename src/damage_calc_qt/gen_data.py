#!/usr/bin/env python3
"""Generate DamageData.cpp from ../damage_calc.py (weapon, attack and
monster tables and the valid weapon+attack pairs of its COMBOS section),
so the Qt tool uses exactly the numbers the Python tools use.

Run:  python3 gen_data.py            (rewrites DamageData.cpp)
"""
import os
import re
import sys

here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(here, ".."))
import damage_calc as engine   # noqa: E402


def b(v):
    return "true" if v else "false"


def pairs():
    with open(os.path.join(here, "..", "damage_calc.py")) as fh:
        src = fh.read()
    m = re.search(r"COMBOS\s*=\s*\[(.*?)\]", src, re.S)
    found = re.findall(r'\(\s*"([^"]+)"\s*,\s*"([^"]+)"\s*\)', m.group(1))
    mapping = {}
    for wn, an in found:
        if wn in engine.WEAPONS and an in engine.ATTACKS:
            mapping.setdefault(wn, [])
            if an not in mapping[wn]:
                mapping[wn].append(an)
    for w in engine.WEAPONS:
        mapping.setdefault(w, sorted(engine.ATTACKS))
    return mapping


def main():
    out = []
    out.append("// GENERATED by gen_data.py from ../damage_calc.py - do not edit.")
    out.append('#include "DamageData.h"')
    out.append("")
    wnames = sorted(engine.WEAPONS)
    anames = sorted(engine.ATTACKS)
    out.append("const std::vector<Weapon> &weapons()\n{\n  static const std::vector<Weapon> v = {")
    for n in wnames:
        w = engine.WEAPONS[n]
        out.append('    {"%s", %d, %d, %d, %d, %s},' % (
            n, w["weight"], w["ubyte1"], w["ubyte2"], w["armor_div"] or 0,
            b(w.get("vorpal"))))
    out.append("  };\n  return v;\n}\n")
    out.append("const std::vector<Attack> &attacks()\n{\n  static const std::vector<Attack> v = {")
    for n in anames:
        a = engine.ATTACKS[n]
        out.append('    {"%s", %d, %d, %d, %d, %d, %d, %s},' % (
            n, a["P7"], a["P8"], a["skill"], a["time"], a["energy"],
            a["exp"], b(a.get("disrupt"))))
    out.append("  };\n  return v;\n}\n")
    out.append("const std::vector<Monster> &monsters()\n{\n  static const std::vector<Monster> v = {")
    mons = [("MONSTER (default: %s)" % engine.MONSTER["name"], engine.MONSTER)]
    nums = sorted((a for a in dir(engine)
                   if a.startswith("MONSTER") and a[7:].isdigit()),
                  key=lambda a: int(a[7:]))
    for a in nums:
        m = getattr(engine, a)
        mons.append(("%s (%s)" % (a, m["name"]), m))
    for label, m in mons:
        out.append('    {"%s", "%s", %d, %d, %d, %d, %d, %s},' % (
            label, m["name"], m["armor"], m["dex"], m["level_difficulty"],
            m["base_health"], m["exp"], b(m["non_material"])))
    out.append("  };\n  return v;\n}\n")
    pm = pairs()
    out.append("// valid attacks of each weapon (index into attacks()), in COMBOS order")
    out.append("const std::vector<std::vector<int>> &weaponAttacks()\n{\n  static const std::vector<std::vector<int>> v = {")
    for n in wnames:
        out.append("    {%s}, // %s" % (
            ", ".join(str(anames.index(a)) for a in pm[n]), n))
    out.append("  };\n  return v;\n}\n")
    c = engine.CHARACTER
    out.append("// the Python defaults (damage_calc.CHARACTER / COMBOS)")
    out.append("const std::vector<std::pair<int, int>> &defaultCombos()\n{\n  static const std::vector<std::pair<int, int>> v = {")
    for wn, an in engine.COMBOS:
        out.append("    {%d, %d}," % (wnames.index(wn), anames.index(an)))
    out.append("  };\n  return v;\n}\n")
    out.append("Character defaultCharacter()\n{\n  Character c;")
    for k in ("strength", "dexterity", "luck", "load", "stamina",
              "max_stamina"):
        out.append("  c.%s = %d;" % (
            {"max_stamina": "maxStamina"}.get(k, k), c[k]))
    for s, v in c["mastery"].items():
        out.append("  c.mastery[%d] = %d;" % (s, v))
    out.append("  return c;\n}")
    with open(os.path.join(here, "DamageData.cpp"), "w") as fh:
        fh.write("\n".join(out) + "\n")


main()
